"""Integration checks on a dedicated LOCAL database, with temporary tables only."""
import copy
from datetime import datetime
import json
import unittest
from unittest.mock import patch

import psycopg
from psycopg.rows import dict_row
from psycopg.types.json import Jsonb

import repair


class RepairTest(unittest.TestCase):
    def setUp(self):
        self.conn = psycopg.connect(host="127.0.0.1", dbname="dbservice_status_repair_tests",
                                   user="postgres", password="postgres", row_factory=dict_row)
        self.addCleanup(self.conn.close)
        self.conn.execute("CREATE TEMP TABLE student(id bigint PRIMARY KEY,user_id bigint,status text,inserted_at timestamp,updated_at timestamp)")
        self.conn.execute("CREATE TEMP TABLE status(id bigint,title text)")
        self.conn.execute("""CREATE TEMP TABLE enrollment_record(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          user_id bigint,group_type text,group_id bigint,is_current boolean,start_date date,end_date date,
          academic_year text,subject_id bigint,inserted_at timestamp,updated_at timestamp)""")
        self.conn.execute("""CREATE TEMP TABLE lms_student_write_audits(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          action text,actor_email text,actor_login_type text,actor_role text,row_counts jsonb,
          affected_identifiers jsonb,created_values jsonb,changed_values jsonb,inserted_at timestamp,updated_at timestamp)""")
        self.conn.execute("INSERT INTO status VALUES(2,'enrolled'),(3,'dropout')")
        self.add_student(1)

    def add_student(self, sid, year="2026-2027"):
        uid = sid * 10
        self.conn.execute("INSERT INTO student VALUES(%s,%s,'enrolled','2026-08-01','2026-08-01')", (sid, uid))
        for kind, gid in (("school", 999), ("batch", 7), ("grade", 3), ("auth_group", 5)):
            self.conn.execute("""INSERT INTO enrollment_record(user_id,group_type,group_id,is_current,start_date,
              academic_year,inserted_at,updated_at) VALUES(%s,%s,%s,true,'2026-07-01',%s,'2026-08-01','2026-08-01')""", (uid, kind, gid, year))
        return self.audit(sid, "student_bulk_create", {"status": "enrolled", "school_id": 9, "batch_pk_id": 7, "grade_id": 3})

    def audit(self, sid, action, created=None, changes=None):
        return self.conn.execute("""INSERT INTO lms_student_write_audits(action,affected_identifiers,
          created_values,changed_values,inserted_at,updated_at) VALUES(%s,%s,%s,%s,'2026-08-01','2026-08-01') RETURNING id""",
          (action, Jsonb({"student_pk_id": sid, "user_id": sid * 10}), Jsonb(created or {}), Jsonb(changes or {}))).fetchone()["id"]

    def report(self):
        return repair.inventory(self.conn, "2026-2027", 36817)

    def apply(self, manifest):
        return repair.apply_manifest(self.conn, manifest, "local-qa@example.invalid")

    def test_count_dates_school_independence_and_idempotency(self):
        report = self.report()
        self.assertEqual(report["summary"]["box_count"], 1)
        self.assertEqual(report["summary"]["change_since_previous"], 1 - 36817)
        self.assertEqual(report["rows"][0]["proposed"]["start_date"], "2026-07-01")
        before = self.conn.execute("SELECT * FROM enrollment_record ORDER BY id").fetchall()
        student = self.conn.execute("SELECT * FROM student").fetchall()
        result = self.apply(report)
        self.assertEqual(result[0]["result"], "created")
        self.assertEqual(self.apply(report)[0]["result"], "already_applied")
        self.assertEqual(self.report()["summary"]["box_count"], 0)
        self.assertEqual(before, self.conn.execute("SELECT * FROM enrollment_record WHERE group_type!='status' ORDER BY id").fetchall())
        self.assertEqual(student, self.conn.execute("SELECT * FROM student").fetchall())
        row = self.conn.execute("SELECT * FROM enrollment_record WHERE group_type='status'").fetchone()
        self.assertGreater(row["inserted_at"], datetime(2026, 8, 1))
        self.assertEqual(row["inserted_at"], row["updated_at"])
        self.assertEqual(self.conn.execute("SELECT count(*) AS n FROM lms_student_write_audits WHERE action=%s", (repair.ACTION,)).fetchone()["n"], 1)

    def test_year_scope_and_uncertain_dates(self):
        self.add_student(2, "2025-2026")
        self.assertEqual(self.report()["summary"]["box_count"], 1)
        self.conn.execute("UPDATE enrollment_record SET start_date='2026-07-02' WHERE group_type='grade' AND user_id=10")
        report = self.report()
        self.assertEqual(report["summary"]["box_count"], 1)
        self.assertEqual(report["rows"], [])
        self.assertEqual(report["summary"]["dispositions"]["box_excluded:ambiguous_start_date"], 1)

    def test_any_existing_status_history_excludes_accidental_undo_group(self):
        self.conn.execute("""INSERT INTO enrollment_record(user_id,group_type,group_id,is_current,start_date,
          end_date,academic_year,inserted_at,updated_at) VALUES(10,'status',3,false,'2026-08-02','2026-08-03','2026-2027','2026-08-02','2026-08-03')""")
        self.assertEqual(self.report()["summary"]["box_count"], 0)
        self.assertEqual(self.report()["rows"], [])

    def test_missing_status_does_not_override_dropout_evidence(self):
        self.audit(1, "student_program_dropout", changes={"status": {"old": "enrolled", "new": "dropout"}})
        self.assertEqual(self.report()["summary"]["box_count"], 1)
        self.assertEqual(self.report()["rows"], [])

    def test_duplicate_enrolled_lookup_fails_closed(self):
        self.conn.execute("INSERT INTO status VALUES(4,'enrolled')")
        self.assertEqual(self.report()["rows"], [])

    def test_stale_batch_rolls_back_earlier_insert(self):
        self.add_student(2)
        manifest = self.report()
        self.conn.execute("UPDATE student SET status='dropout' WHERE id=2")
        with self.assertRaisesRegex(ValueError, "Evidence changed"):
            with self.conn.transaction():
                self.apply(manifest)
        self.assertEqual(self.conn.execute("SELECT count(*) AS n FROM enrollment_record WHERE group_type='status'").fetchone()["n"], 0)
        self.assertEqual(self.conn.execute("SELECT count(*) AS n FROM lms_student_write_audits WHERE action=%s", (repair.ACTION,)).fetchone()["n"], 0)

    def test_changed_membership_and_changed_repaired_row_are_rejected(self):
        manifest = self.report()
        self.conn.execute("UPDATE enrollment_record SET updated_at='2026-08-02' WHERE group_type='school'")
        with self.assertRaisesRegex(ValueError, "Evidence changed"):
            self.apply(manifest)
        manifest = self.report()
        self.apply(manifest)
        self.conn.execute("UPDATE enrollment_record SET is_current=false WHERE group_type='status'")
        with self.assertRaisesRegex(ValueError, "Repaired row changed"):
            self.apply(manifest)

    def test_duplicate_creation_audit_and_owner_mismatch(self):
        self.audit(1, "student_bulk_create", {"status": "enrolled", "grade_id": 3, "batch_pk_id": 7})
        self.assertEqual(self.report()["rows"], [])
        self.conn.execute("DELETE FROM lms_student_write_audits WHERE id=(SELECT max(id) FROM lms_student_write_audits)")
        self.conn.execute("UPDATE lms_student_write_audits SET affected_identifiers=jsonb_set(affected_identifiers,'{user_id}','99')")
        self.assertEqual(self.report()["rows"], [])

    def test_audited_batch_replacement_keeps_original_status_start(self):
        self.conn.execute("UPDATE enrollment_record SET is_current=false,end_date='2026-08-02' WHERE group_type='batch'")
        self.conn.execute("""INSERT INTO enrollment_record(user_id,group_type,group_id,is_current,start_date,
          academic_year,inserted_at,updated_at) VALUES(10,'batch',8,true,'2026-08-02','2026-2027','2026-08-02','2026-08-02')""")
        self.assertEqual(self.report()["rows"], [])
        self.audit(1, "student_update", changes={"batch_id": {"old": 7, "new": 8}})
        manifest = self.report()
        self.assertEqual(manifest["rows"][0]["proposed"]["start_date"], "2026-07-01")
        self.assertEqual(self.apply(manifest)[0]["result"], "created")

    def test_local_guard_rejects_production_name_without_connecting(self):
        with patch("psycopg.connect") as connect:
            with self.assertRaisesRegex(ValueError, "Only dedicated"):
                repair.connect_local("prod_af_db", 5432)
            connect.assert_not_called()

    def test_manifest_code_database_and_payload_changes_are_rejected(self):
        for key, value in (("script_sha256", "changed"), ("database", "another_database")):
            manifest = self.report()
            manifest[key] = value
            with self.assertRaises(ValueError):
                self.apply(manifest)
        manifest = self.report()
        manifest["rows"][0]["proposed"]["group_id"] = 3
        with self.assertRaisesRegex(ValueError, "Evidence changed"):
            self.apply(manifest)


if __name__ == "__main__":
    unittest.main()
